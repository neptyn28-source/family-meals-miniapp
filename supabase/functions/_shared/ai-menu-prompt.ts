function goalLabel(goal: string) {
  return ({ lose: "снижение веса", maintain: "поддержание", gain: "набор веса" } as Record<string, string>)[goal] || goal;
}

function stateLabel(state: string) {
  return ({
    raw: "сырое",
    cooked: "готовое",
    semi_finished: "полуфабрикат",
    frozen: "замороженное",
    dry: "сухое",
    canned: "консервы",
  } as Record<string, string>)[state] || state;
}

function dateLabel(date: string | null | undefined) {
  return date ? String(date) : "не указан";
}

/** Блюдо из прошлых недель: чтобы ИИ видел, что уже было, и не повторялся. */
export type RecentDish = { week_start: string; title: string; meal_types: string[] };

const TRAINING_FACTOR: Record<string, number> = { "0": 1.2, "1-2": 1.3, "3-4": 1.375, "5+": 1.465 };

/**
 * Ориентир на день для взрослого: Миффлин — Сан Жеор × активность, минус дефицит
 * (15% умеренно, 30% быстрее; не ниже 1800 ккал мужу и 1400 жене), белок 1,8 г/кг мужу и 1,6 г/кг жене.
 * Без веса, роста или возраста ориентира нет — ИИ подбирает по отзывам.
 */
export function dailyTarget(p: any, sex: "male" | "female") {
  const w = Number(p?.weight_kg), h = Number(p?.height_cm), a = Number(p?.age_years);
  if (!(w > 0 && h > 0 && a > 0)) return null;
  const bmr = 10 * w + 6.25 * h - 5 * a + (sex === "male" ? 5 : -161);
  const factor = TRAINING_FACTOR[String(p?.training_frequency ?? "0")] ?? 1.2;
  const deficit = p?.goal === "lose" ? (p?.weight_loss_pace === "faster" ? 0.7 : 0.85) : 1;
  const kcal = Math.max(sex === "male" ? 1800 : 1400, Math.round((bmr * factor * deficit) / 50) * 50);
  const protein = Math.round(w * (sex === "male" ? 1.8 : 1.6) / 5) * 5;
  return { kcal, protein };
}

const MEAL_TEXT: Record<string, string> = {
  breakfast: "завтрак", snack1: "перекус", snack2: "перекус", lunch: "обед", dinner: "ужин",
};

function recentDishLines(recent: RecentDish[]) {
  const byWeek = new Map<string, string[]>();
  for (const d of recent) {
    const kinds = [...new Set(d.meal_types.map((m) => MEAL_TEXT[m] ?? m))].join("/");
    const line = `${d.title}${kinds ? ` (${kinds})` : ""}`;
    const list = byWeek.get(d.week_start) ?? [];
    if (!list.includes(line)) list.push(line);
    byWeek.set(d.week_start, list);
  }
  return [...byWeek.entries()]
    .sort(([a], [b]) => b.localeCompare(a))
    .map(([week, list]) => `Неделя ${week}: ${list.join("; ")}.`);
}

